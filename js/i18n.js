let currentLang = 'zh-TW';

// 偵測使用者語言：優先讀 URL 路徑（/ja /en /zh /th），再讀 ?lang= 參數，再讀 localStorage，否則讀瀏覽器語言
function detectLang() {
	// 1. URL 路徑優先（SEO 多語言路由）
	const path = location.pathname;
	if (path.match(/\/ja(\/|$)/) && I18N['ja']) return 'ja';
	if (path.match(/\/en(\/|$)/) && I18N['en']) return 'en';
	if (path.match(/\/zh(\/|$)/) && I18N['zh-CN']) return 'zh-CN';
	if (path.match(/\/tw(\/|$)/) && I18N['zh-TW']) return 'zh-TW';
	if (path.match(/\/th(\/|$)/) && I18N['th']) return 'th';

	// 2. ?lang= 參數（給 iframe 用）
	const urlLang = new URLSearchParams(location.search).get('lang');
	if (urlLang && I18N[urlLang]) return urlLang;

	// 3. 使用者手動選過就用 localStorage 的
	const saved = localStorage.getItem('apng-lang');
	if (saved && I18N[saved]) return saved;

	// 4. 讀瀏覽器語言
	const nav = (navigator.language || 'zh-TW').toLowerCase();
	if (nav.startsWith('zh')) {
		// zh-CN / zh-SG 視為簡中，其餘 zh 視為繁中
		if (nav.includes('cn') || nav.includes('sg') || nav.includes('hans')) return 'zh-CN';
		return 'zh-TW';
	}
	if (nav.startsWith('ja')) return 'ja';
	if (nav.startsWith('th')) return 'th';
	return 'en'; // 預設英文
}

// 翻譯函式：取目前語言的字串，支援 {變數} 插值
function t(key, vars) {
	let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N['zh-TW'][key] || key;
	if (vars) {
		for (const k in vars) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
	}
	return s;
}

// 套用語言：掃所有 data-i18n 屬性的元素，替換成對應語言
function applyLang(lang) {
	currentLang = lang;
	localStorage.setItem('apng-lang', lang);
	document.documentElement.lang = lang === 'zh-CN' ? 'zh-CN' : lang.toLowerCase();
	document.title = t('title');
	// 掃所有 data-i18n 節點（用 innerHTML 才能渲染裡面的 <span class="cat"> emoji）
	document.querySelectorAll('[data-i18n]').forEach(el => {
		el.innerHTML = t(el.dataset.i18n);
	});
	document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
		el.placeholder = t(el.dataset.i18nPlaceholder);
	});
	// 掃 data-i18n-title（按鈕的滑鼠懸停提示）
	document.querySelectorAll('[data-i18n-title]').forEach(el => {
		el.title = t(el.dataset.i18nTitle);
	});
	// 掃 data-i18n-img：圖片路徑可以寫 {lang} 佔位符，切語言時自動換成對應語系的圖
	// 例：<img data-i18n-img="images/sample/colors-{lang}.jpg">
	//     zh-TW → colors-zh-TW.jpg、zh-CN → colors-zh-CN.jpg、en / ja / th 同理
	// 這樣同一段 HTML 不用為每個語系各寫一個 <img>，也不必多開一堆 i18n key
	document.querySelectorAll('[data-i18n-img]').forEach(el => {
		el.src = el.dataset.i18nImg.replace(/\{lang\}/g, currentLang);
	});
	// 更新語言下拉的選中狀態
	const btn = document.getElementById('langBtn');
	if (btn) {
		const item = document.querySelector('.lang-menu li[data-value="' + lang + '"]');
		if (item) {
			// 更新 emoji
			const itemCat = item.querySelector('.cat');
			const btnCat = btn.querySelector('.cat');
			if (itemCat && btnCat) {
				btnCat.className = itemCat.className;
			}
			// 更新文字
			const label = btn.querySelector('.lang-label');
			if (label) label.textContent = item.textContent.trim();
		}
	}
	// 切換語言後重建影格卡片，讓動態產生的 title 也跟著變
	if (typeof rebuildPreviews === 'function') rebuildPreviews();
	// 切換語言後重繪 PNG 靜態貼圖的警告列（文字是點擊時動態產生、沒有 data-i18n，需重跑一次）
	if (typeof window.renderPngStickerWarnings === 'function') window.renderPngStickerWarnings();
	// 切換語言後重繪 APNG 生成結果的警告列與摘要文字（同樣是生成當下寫死的）
	if (typeof window.renderApngTexts === 'function') window.renderApngTexts();
	// 切換語言後重建 Meme 頁面（空狀態提示等動態文字）
	if (typeof window.renderMemes === 'function') window.renderMemes();
}

// 語言切換：自訂下拉（直接綁定，不依賴 DOMContentLoaded）
function initLangDropdown() {
	const dropdown = document.getElementById('langDropdown');
	const btn = document.getElementById('langBtn');
	const menu = document.getElementById('langMenu');
	if (!dropdown || !btn || !menu) {
		// DOM 還沒載入，等一下再試
		setTimeout(initLangDropdown, 50);
		return;
	}

	// 點按鈕開關選單
	btn.onclick = (e) => {
		e.stopPropagation();
		menu.classList.toggle('open');
	};
	// 點選單項目
	menu.querySelectorAll('li').forEach(li => {
		li.onclick = () => {
			applyLang(li.dataset.value);
			menu.classList.remove('open');
		};
	});
	// 點外面關閉
	document.onclick = () => menu.classList.remove('open');
	applyLang(detectLang());
}
initLangDropdown();
